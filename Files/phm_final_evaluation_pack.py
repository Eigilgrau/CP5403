"""Consolidate saved results and prepare unscored human review. No inference."""
import hashlib
import json
from collections import Counter
from datetime import datetime
from pathlib import Path
import statistics

from phm_final_metrics import classification
from phm_diagnosis import fingerprint
from phm_run_reporting import atomic_json,atomic_text

RUN='20261122T103151_paired_CD_two_stage_heldout_13ba4e1a'
OUT='Outputs/final_evaluation_v1'
DIMS={
 'factual_accuracy':'Do stated values, comparisons and descriptions match the supplied evidence?',
 'citation_support':'Do the cited cases or passages support the claims attributed to them?',
 'diagnostic_reasoning':'Does the explanation justify its inference without treating similarity as proof or inventing physical meanings/thresholds?',
 'uncertainty':'Does it acknowledge relevant uncertainty, conflicting evidence and the limits of recorded labels?'}


def read(path):return json.loads(Path(path).read_text(encoding='utf-8'))
def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def rank(value):return hashlib.sha256(('5403|human-review-v1|'+value).encode()).hexdigest()


def build(root):
    root=Path(root);source=root/'Outputs/runs'/RUN;out=root/OUT
    metrics=read(source/'final_evaluation_metrics.json');rows=read(source/'paired_results.json')
    assert sha(source/'paired_results.json')==metrics['paired_results_sha256']
    assert len(rows)==200 and len({r['case_id'] for r in rows})==100
    explanations=read(source/'explanation_responses.json');decisions=read(source/'decision_responses.json')
    requests=[json.loads(line) for line in (source/'explanation_requests.jsonl').read_text(encoding='utf-8').splitlines()]
    lookup={q['request_id']:q for q in requests}
    for response in explanations+decisions:
        raw=response['response']
        assert raw['origin']=='model_inference' and raw['raw_output_sha256']==fingerprint(raw['raw_output'])
    summary={}
    for c in ('C','D'):
        group=[r for r in rows if r['condition']==c];m=classification(group)
        assert abs(m['accuracy']-metrics['conditions'][c]['accuracy'])<1e-12
        assert abs(m['macro_f1']-metrics['conditions'][c]['macro_f1'])<1e-12
        ex=[r for r in explanations if r['condition']==c];parseable=0
        for r in ex:
            try:json.loads(r['response']['raw_output']);parseable+=1
            except (ValueError,TypeError):pass
        summary[c]={**metrics['conditions'][c],
            'parseable_explanations':parseable,'unparseable_explanations':len(ex)-parseable,
            'explanation_token_limit_hits':sum(bool(r['response'].get('generation_hit_limit')) for r in ex),
            'explanation_error_counts':dict(Counter(e for r in ex for e in r['checks'].get('errors',[]))),
            'total_generation_seconds':sum(r['generation_seconds'] for r in group),
            'median_two_stage_generation_seconds':statistics.median(r['generation_seconds'] for r in group),
            'total_input_tokens':sum(r['input_tokens'] for r in group),'total_output_tokens':sum(r['output_tokens'] for r in group)}
    report=read(source/'run_report.json')
    elapsed=(datetime.fromisoformat(report['updated_utc'])-datetime.fromisoformat(report['started_utc'])).total_seconds()
    atomic_json(out/'consolidated_metrics.json',{'source_run':RUN,'scope':'Original frozen held-out version only',
        'conditions':summary,'paired_D_minus_C':metrics['paired_D_minus_C'],
        'paired_prediction_disagreements':metrics['paired_prediction_disagreements'],
        'uncertainty':metrics['site_cluster_bootstrap'],'wall_clock_seconds':elapsed,
        'cost_interpretation':'Generation totals exclude model loading/retrieval. Notebook duration includes other work. No monetary/compute-unit estimate inferred.',
        'human_review_status':'pending; not generated by assistant'})
    # Select paired cases without using labels, correctness, completeness or judgement.
    ids=sorted({r['case_id'] for r in explanations},key=rank)[:10]
    chosen=[r for r in explanations if r['case_id'] in ids]
    assert len(chosen)==20
    chosen.sort(key=lambda r:rank(r['request_id']+'|presentation'))
    packet=[];key=[]
    for i,r in enumerate(chosen,1):
        q=lookup[r['request_id']];payload=json.loads(q['messages'][1]['content'])
        item_id=f'R{i:02d}';query=dict(payload['query']);query.pop('case_id',None)
        raw=r['response']['raw_output']
        try:parsed=json.loads(raw);complete=True
        except (ValueError,TypeError):parsed=None;complete=False
        packet.append({'item_id':item_id,'raw_output':raw,'complete_json':complete,
            'readable_output':parsed,'query':query,'historical_cases':payload['historical_cases'],
            'feature_order':payload['feature_order'],'feature_notes':payload.get('feature_notes',[]),
            'literature':q.get('literature',[]),'saved_decision':payload.get('saved_qwen_decision',{})})
        key.append({'item_id':item_id,'case_id':r['case_id'],'condition':r['condition'],
                    'request_id':r['request_id'],'original_output_status':r['checks']['status']})
    protocol={'version':'human-review-v1','source_run':RUN,'sample_cases':10,'sample_outputs':20,
        'selection':'First ten case IDs by SHA256(5403|human-review-v1|case_id); both C/D, independently hash-ordered for presentation. No quality, label or correctness selection.',
        'assessor':'Project author, one human reviewer; not independent expert validation. Assistant prepares materials but supplies no human ratings.',
        'masking':'Condition names and reference query outcomes hidden in review UI. Literature presence and prior project involvement prevent full blinding.',
        'unit':'Whole visible explanation, not claim-level statistics. Rate complete or partial visible claims; do not reconstruct missing text.',
        'dimensions':DIMS,'scale':{'2':'Adequate: all assessable relevant statements meet criterion.','1':'Partial/mixed: meaningful strengths and weaknesses.','0':'Inadequate: materially contradicted/unsupported content or absent necessary uncertainty.','U':'Unable to assess from visible output and provided evidence.','NA':'No applicable claim (e.g. no numerical claims for factual accuracy); explain why.'},
        'incomplete_outputs':'Retained in sample and separately reported as incomplete. Assess visible statements if possible. Use U for missing/unjudgeable content; never assume a truncated response is correct or repair it.',
        'notes':'One brief evidence-based note per item is required, citing a value, feature or source ID and the reason for the rating.',
        'aggregation':'Report counts for 0/1/2/U/NA by dimension and condition. Any numeric mean uses assessable 0/1/2 only, with denominator and missingness shown. No single validity/grounding pass rate or agreement statistic.',
        'limits':'Small sample, single developer-reviewer, possible prior exposure and bias. Post-hoc descriptive audit, no inter-rater reliability, no independent ground-truth benchmark.'}
    encoded=json.dumps({'protocol':protocol,'items':packet},ensure_ascii=False,sort_keys=True)
    packet_hash=hashlib.sha256(encoded.encode()).hexdigest()
    public={'packet_id':packet_hash,'protocol':protocol,'items':packet}
    atomic_json(out/'human_review/review_packet.json',public)
    atomic_json(out/'human_review/analysis_only_sample_key.json',key)
    atomic_json(out/'human_review/sample_status.json',{'outputs':20,'complete_json':sum(r['complete_json'] for r in packet),
        'original_contract_status_counts':dict(Counter(r['original_output_status'] for r in key)),'ratings':'pending'})
    atomic_json(out/'source_manifest.json',{'source_run':RUN,'files':{n:sha(source/n) for n in ['paired_results.json','final_evaluation_metrics.json','explanation_requests.jsonl','explanation_responses.json','decision_responses.json','run_report.json']},'review_packet_id':packet_hash})
    template=(root/'Files/phm_human_review_template.html').read_text(encoding='utf-8')
    atomic_text(out/'human_review/START_REVIEW.html',template.replace('__PACKET_JSON__',json.dumps(public,ensure_ascii=False).replace('<','\\u003c')))
    c,d=summary['C'],summary['D']
    atomic_text(out/'EVALUATION_SUMMARY.txt',f'''FINAL EVALUATION — ORIGINAL FROZEN HELD-OUT VERSION
Source: {RUN}
100 cases, 10 held-out sites: 96 NoRecordedTarget, 2 RuntimeExcessive, 2 SupplyTempTooCold.

Metric                                  C             D
Accuracy                                {c['accuracy']:.2%}        {d['accuracy']:.2%}
Macro F1                                {c['macro_f1']:.4f}        {d['macro_f1']:.4f}
Valid classification                    100/100       100/100
Contract-valid explanation              {c['explanation_valid']}/100        {d['explanation_valid']}/100
Parseable explanation                   {c['parseable_explanations']}/100        {d['parseable_explanations']}/100
Correct and full-output valid           {c['correct_and_full_valid']}/100         {d['correct_and_full_valid']}/100
Mean generation seconds, both stages    {c['mean_generation_seconds']:.2f}         {d['mean_generation_seconds']:.2f}
Mean input tokens, both stages          {c['mean_input_tokens']:.2f}       {d['mean_input_tokens']:.2f}
Mean output tokens, both stages         {c['mean_output_tokens']:.2f}        {d['mean_output_tokens']:.2f}

Only one paired prediction differs: D changes a correct NoRecordedTarget prediction into a fault prediction. D-C accuracy: -1 percentage point; paired site-bootstrap 95% interval [-3,0] points. Only ten clusters; these intervals do not establish population representativeness or capture model-selection uncertainty.
Both conditions identify all four recorded fault cases, but those supports are too small to establish dependable sensitivity. C assigns fault labels to 48/96 NoRecordedTarget cases; D to 49/96. NoRecordedTarget is absence of a recorded target, not proven health. An always-NoRecordedTarget descriptive reference scores 96% accuracy but misses all four faults; it is not an additional experimental condition.
Explanation failures remain in the denominator. {c['explanation_token_limit_hits']} C and {d['explanation_token_limit_hits']} D explanations hit the token cap; token-cap hits and parse failures are overlapping, not identical counts. Numerical-prose policy violations are not automatically incorrect arithmetic. Contract validity is not semantic grounding.
Total run wall-clock: {elapsed/3600:.2f} hours. Generation costs exclude loading/retrieval and are not paid compute-unit estimates. All timings refer to this recorded runtime, not universal model speed.

VERSION BOUNDARIES
These performance results apply only to the original frozen two-stage model. Later structured-output checks were development-only; their validity rates are not independent accuracy results. The attempted override revision failed output completion. The subsequent temporal/component retrieval revision failed its predeclared local continuation checks and was not promoted. Original held-out outcomes were never replaced by those later results.

EXPLANATION REVIEW — PENDING
A fixed sample of ten cases / twenty paired explanations is prepared. No human ratings exist yet. Review includes incomplete outputs; no selection for successful examples. The user is the single developer-reviewer, not an independent expert. Assistant reviews and earlier unvalidated LLM judges do not count as human ground truth. Do not claim evaluated semantic grounding until actual ratings are recorded and their limitations reported.

ASSESSMENT REPORTING
Report implementation, classification/completion/cost evidence, and negative findings separately. Full fluent evidence-grounded explanation remains unmet. Do not claim the later engineering version inherits the original accuracy. Acknowledge GenAI assistance, use verified APA7 references, and keep presentation-feedback reflection separate from debugging history.
''')
    print('Prepared',out,'with 20 UNRATED outputs; complete JSON:',sum(r['complete_json'] for r in packet))


if __name__=='__main__':build(Path(__file__).resolve().parent.parent)
